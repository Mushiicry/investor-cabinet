/**
 * Единый источник правды по состоянию аккаунта для V2-экранов.
 *
 * Пустой / кастдев-аккаунт — кошельки ещё не подключены, портфель по нулям.
 * Нули здесь означают ОТСУТСТВИЕ ДАННЫХ, а не критический риск: экраны должны
 * показывать нейтральный «нет данных», а не тревожные красные сигналы.
 *
 * Раньше проверка `totalPortfolioValue <= 0` была скопирована в 6 компонентах —
 * теперь правило живёт в одном месте. Если определение «пустого аккаунта» изменится
 * (например, ещё и по числу позиций), правим только здесь, а не в каждом экране.
 *
 * Реальный аккаунт (value > 0) под этот предикат не попадает — risk-логика не меняется.
 */
export function isEmptyAccount(portfolio: { totalPortfolioValue: number }): boolean {
  return portfolio.totalPortfolioValue <= 0;
}
